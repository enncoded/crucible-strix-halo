"""spec_sweep config for the stock/tuned head A/B on the tree-draft prompts.

  python3 training/mtp_tune/measure_cfg.py ROOT OUT.cfg [--n 256] [--groups code,prose,tool,think]

Per prompt: a serial reference, the production default (spec 7, Q0.3, 64K head) and forced depth 7 (Q0).
The sidecar is chosen by the environment (CRUCIBLE_MTP_SIDECAR), so one config serves both arms.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODES = {"serial": "--spec 0", "default": "--spec 7 --draft-q 0.3", "forced": "--spec 7 --draft-q 0"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("out")
    ap.add_argument("--n", type=int, default=256)
    ap.add_argument("--groups", default="code,prose,tool,think")
    ap.add_argument("--modes", default="serial,default,forced")
    a = ap.parse_args()
    man = json.loads((ROOT / "bench/tree_draft/manifest.json").read_text())
    lines = ["# generated by training/mtp_tune/measure_cfg.py"]
    for p in man["prompts"]:
        if p["category"] not in a.groups.split(","):
            continue
        for mode in a.modes.split(","):
            lines.append(f"{p['name']}.{mode} --ids-file {a.root}/bench/tree_draft/{p['ids_file']} --n {a.n} "
                         f"--prefill 4096 --draft-head 64k --mtp-prefix 256 {MODES[mode]}")
    Path(a.out).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
