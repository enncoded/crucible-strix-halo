#!/usr/bin/env python3
"""Layer-0 FP64 oracle fixture using the actual checkpoint and prompt IDs.

Isolates non-GEMM numerics: projections are generated by oracle.linear, then
rounded to fp32 just as the standalone GDN harness expects. oracle_y/state
use unrounded projections, so their error includes this controlled boundary.
"""
import argparse
from pathlib import Path
import numpy as np
import oracle


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("ckpt")
    ap.add_argument("ids")
    ap.add_argument("out")
    ap.add_argument("--rows", type=int, default=256)
    ap.add_argument("--layer", type=int, default=0)
    ap.add_argument("--dump", help="residual dump used as a teacher-forced input stack")
    args = ap.parse_args()
    if args.layer < 0 or args.layer >= 48 or args.layer % 4 == 3:
        ap.error("layer must name a GDN layer in 0..47")
    if args.layer and not args.dump:
        ap.error("layers above zero require --dump")
    ck = oracle.Ckpt(args.ckpt)
    ids = np.array([int(v) for v in Path(args.ids).read_text().strip().split(",")])
    ids = np.resize(ids, args.rows)
    if args.dump:
        stack = np.fromfile(Path(args.dump) / f"h_{args.layer:02d}.f32", np.float32).reshape(-1, 4, 2560)
        if len(stack) < args.rows:
            ap.error("the input dump has fewer rows than requested")
        stack = stack[:args.rows].astype(np.float64)
    else:
        embed = ck.f64("model.language_model.embed_tokens.weight")[ids]
        stack = np.repeat(embed[:, None, :], 4, axis=1)
    if args.layer == 1:
        stack = oracle.ple(ck, stack, ids)
    prefix = f"model.language_model.layers.{args.layer}."
    x, _ = oracle.hc_read(ck, prefix + "attn_hyper_connection.", stack)
    p = prefix + "linear_attn."
    qkv = oracle.linear(ck, p + "in_proj_qkv", x)
    z = oracle.linear(ck, p + "in_proj_z", x)
    ab = np.concatenate([ck.f64(p + "in_proj_a.weight"), ck.f64(p + "in_proj_b.weight")])
    ab_logits = x @ ab.T
    conv = ck.f64(p + "conv1d.weight")[:, 0, :]
    alog, dt = ck.f64(p + "A_log"), ck.f64(p + "dt_bias")
    gamma = ck.f64(p + "norm.weight")
    pad = np.concatenate([np.zeros((3, 10240)), qkv])
    c = oracle.silu(sum(conv[:, t] * pad[t:t + args.rows] for t in range(4)))
    q = c[:, :2048].reshape(-1, 16, 128)
    k = c[:, 2048:4096].reshape(-1, 16, 128)
    v = c[:, 4096:].reshape(-1, 48, 128)
    q = q / np.sqrt((q * q).sum(-1, keepdims=True) + oracle.EPS) / np.sqrt(128)
    k = k / np.sqrt((k * k).sum(-1, keepdims=True) + oracle.EPS)
    q, k = np.repeat(q, 3, axis=1), np.repeat(k, 3, axis=1)
    sp = ab_logits[:, :48] + dt
    g = -np.exp(alog) * np.where(sp > 20, sp, np.log1p(np.exp(np.minimum(sp, 20))))
    decay, beta = np.exp(g), oracle.sigmoid(ab_logits[:, 48:])
    state = np.zeros((48, 128, 128))
    y = np.empty((args.rows, 48, 128))
    for t in range(args.rows):
        sd = state * decay[t, :, None, None]
        mem = np.einsum("hij,hi->hj", sd, k[t])
        delta = beta[t, :, None] * (v[t] - mem)
        state = sd + k[t, :, :, None] * delta[:, None, :]
        y[t] = np.einsum("hij,hi->hj", state, q[t])
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "rows.txt").write_text(f"{args.rows}\n")
    values = {"qkv": qkv, "z": z, "x": x, "ab_logits": ab_logits,
              "conv": conv, "alog": alog, "dt": dt, "gamma": gamma}
    for name, value in values.items():
        value.astype(np.float32).tofile(out / f"{name}.f32")
    ab.astype(np.float16).tofile(out / "ab.f16")
    ck.t(p + "out_proj.suh").numpy().tofile(out / "suh.f16")
    y.tofile(out / "oracle_y.f64")
    state.tofile(out / "oracle_state.f64")
    print(f"layer={args.layer} rows={args.rows} fixture={out}")


if __name__ == "__main__":
    main()
